"""Shop structure of the industrial case from the public process table (data/case/process.yaml, new code).

``load_case_structure`` turns the table into the benchmark file layout: ``machine_division`` (machines per
stage), the global machine order and a ``[products, machines]`` processing-time matrix with 0 for machines a
product cannot use (``data/instance_io.py`` treats 0 as "not eligible"). Case instances are generated by
``data/generator.py`` with this fixed structure (pool kind ``case``); times are minutes.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import List

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PROCESS_FILE = ROOT / "data" / "case" / "process.yaml"


@dataclass(frozen=True)
class ShopStructure:
    n_products: int
    machine_division: List[int]
    machines: List[str]
    process_times: np.ndarray          # [products, machines]; 0 = not eligible
    unit: str = "second"
    product_names: tuple = ()

    @property
    def n_stages(self) -> int:
        return len(self.machine_division)

    @property
    def n_machines(self) -> int:
        return int(sum(self.machine_division))


def load_case_structure(path: str | Path = DEFAULT_PROCESS_FILE) -> ShopStructure:
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8"))
    machines: List[str] = []
    division: List[int] = []
    for stage in data["stages"]:
        ids = [str(m) for m in stage["machines"]]
        division.append(len(ids))
        machines.extend(ids)
    if len(set(machines)) != len(machines):
        raise ValueError("duplicate machine ids in the case process table")
    index = {m: i for i, m in enumerate(machines)}
    products = data["products"]
    times = np.zeros((len(products), len(machines)), dtype=np.int64)
    for p, product in enumerate(products):
        for machine, minutes in product["times"].items():
            if str(machine) not in index:
                raise KeyError(f"unknown machine {machine!r} for product {product.get('name')!r}")
            times[p, index[str(machine)]] = int(minutes)
        for stage, stage_machines in enumerate(data["stages"]):
            ids = [index[str(m)] for m in stage_machines["machines"]]
            if not any(times[p, i] > 0 for i in ids):
                raise ValueError(f"product {product.get('name')!r} has no eligible machine in stage {stage + 1}")
    return ShopStructure(n_products=len(products), machine_division=division, machines=machines,
                         process_times=times, unit=str(data.get("unit", "second")),
                         product_names=tuple(str(p.get("name", "")) for p in products))
